/**
 * User Referral Controller — API handlers for User → User referral operations.
 *
 * Routes:
 *   POST /api/user-referrals/generate  — generate a new referral code
 *   GET  /api/user-referrals/my        — list user's referral codes
 *   GET  /api/user-referrals/validate/:code — validate a code (public)
 *
 * Pandit Referral (referral.controller.js) is completely untouched.
 */

const userReferralService = require('../services/userReferralService');
const walletService = require('../services/walletService');
const settings = require('../utils/settingsService');
const { urls } = require('../config');

const BASE_URL = () => urls.clientUrl;

// ── POST /api/user-referrals/generate ────────────────────────────────────────
/**
 * Generate a new referral code for the authenticated user.
 *
 * Enforces:
 *   - Referral system enabled (admin toggle)
 *   - Daily generation limit (5 per day by default)
 *   - Random code generation with collision retry
 *
 * Body: {} (no body required)
 * Auth: required (user role)
 */
exports.generateCode = async (req, res, next) => {
  try {
    const result = await userReferralService.generateCode(req.user._id);

    // Build the shareable referral link
    const referralLink = `${BASE_URL()}/register?ref=${result.code}`;

    res.status(201).json({
      success: true,
      code: result.code,
      expiresAt: result.expiresAt,
      referralLink,
      referralCodeId: result.referralCodeId,
    });
  } catch (err) {
    if (err.status) {
      return res.status(err.status).json({ success: false, message: err.message });
    }
    next(err);
  }
};

// ── GET /api/user-referrals/my ───────────────────────────────────────────────
/**
 * List all referral codes generated by the authenticated user.
 *
 * Query params: page, limit
 * Auth: required (user role)
 */
exports.listMyCodes = async (req, res, next) => {
  try {
    const { page = 1, limit = 20 } = req.query;
    const { codes, total, page: currentPage } = await userReferralService.listUserCodes(
      req.user._id,
      { page, limit }
    );

    // Enrich codes with shareable links and status labels
    const enriched = codes.map((code) => ({
      ...code,
      referralLink: `${BASE_URL()}/register?ref=${code.code}`,
      isExpired: code.status === 'AVAILABLE' && code.expiresAt < new Date(),
    }));

    res.json({
      success: true,
      codes: enriched,
      total,
      page: currentPage,
    });
  } catch (err) {
    next(err);
  }
};

// ── GET /api/user-referrals/validate/:code ───────────────────────────────────
/**
 * Validate a referral code and return referrer info.
 * Used by the registration page to auto-fill and show referrer name.
 *
 * Public endpoint — no auth required.
 */
exports.validateCode = async (req, res, next) => {
  try {
    const { code } = req.params;
    const result = await userReferralService.validateCode(code);

    if (!result.valid) {
      return res.status(404).json({ success: false, message: 'Invalid or expired referral code' });
    }

    res.json({
      success: true,
      referrerName: result.referrerName,
      codeId: result.codeId,
    });
  } catch (err) {
    next(err);
  }
};

// ── GET /api/user-referrals/settings (admin-facing, read-only for now) ──────
/**
 * Get current user referral system settings (read-only).
 * Useful for the frontend to know: enabled, daily limit, etc.
 * Full admin CRUD will be added in the Admin phase.
 */
exports.getSettings = async (req, res, next) => {
  try {
    const [
      enabled,
      validityDays,
      dailyLimit,
      registrationReward,
      bookingReward,
    ] = await Promise.all([
      settings.get('userReferralEnabled', false),
      settings.get('userReferralDefaultValidityDays', 30),
      settings.get('userReferralDailyLimit', 5),
      settings.get('userReferralRegistrationRewardCoins', 10),
      settings.get('userReferralBookingRewardCoins', 50),
    ]);

    res.json({
      success: true,
      settings: {
        enabled,
        validityDays,
        dailyLimit,
        registrationRewardCoins: registrationReward,
        bookingRewardCoins: bookingReward,
      },
    });
  } catch (err) {
    next(err);
  }
};
