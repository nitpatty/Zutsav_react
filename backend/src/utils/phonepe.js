const axios    = require('axios');
const crypto   = require('crypto');
const settings = require('./settingsService');
const paymentConfig = require('../config/payment.config');

/**
 * PhonePe gateway wrapper.
 *
 * Modes (resolved by config/payment.config.js — see that file for the full
 * precedence rules):
 *   mock     in-process simulation, no HTTP, no credentials
 *   sandbox  PhonePe sandbox with explicitly configured credentials
 *   live     PhonePe production with explicitly configured credentials
 *
 * There are no hardcoded merchant/salt fallbacks anywhere in this module.
 */

// ── Checksum helpers ────────────────────────────────────────────────────────

function sha256Hex(input) {
  return crypto.createHash('sha256').update(input).digest('hex');
}

function checksumOf(payload, salt, saltIndex) {
  return sha256Hex(payload + salt) + '###' + saltIndex;
}

/** Constant-time comparison; unequal lengths are just "not equal". */
function checksumEquals(expected, actual) {
  const a = Buffer.from(String(expected == null ? '' : expected), 'utf8');
  const b = Buffer.from(String(actual   == null ? '' : actual),   'utf8');
  if (a.length !== b.length || a.length === 0) return false;
  return crypto.timingSafeEqual(a, b);
}

// ── Mock gateway state (mock mode ONLY) ─────────────────────────────────────
// Shared across backend workers: outcomes live in the application's own
// MongoDB (MockPaymentState) whenever a database connection is available, so
// an outcome driven on one worker is observed by every other worker — status
// checks, the control plane and webhook verification all read the same state.
// Without a connection (isolated unit tests) the store degrades to
// process-local memory. Mock mode itself is refused in production
// (config/payment.config.js) and its routes are never mounted there
// (src/app.js), so neither path is reachable in production.
const mongoose           = require('mongoose');
const MockPaymentState   = require('../models/MockPaymentState');

const mockOutcomes    = new Map(); // process-local mirror / no-database fallback
const MOCK_SALT_INDEX = '1';

/** Logical TTL: after this, reads return 'pending' — never the default success. */
const MOCK_OUTCOME_TTL_MS  = 24 * 60 * 60 * 1000;
/** Physical TTL: MongoDB deletes the document this long after it was written. */
const MOCK_PHYSICAL_TTL_MS = 30 * 24 * 60 * 60 * 1000;

const dbConnected = () => mongoose.connection.readyState === 1;

/**
 * Mock-mode webhook secret, derived deterministically from JWT_SECRET (which
 * validate.js requires in every environment). Every backend worker therefore
 * computes the SAME secret, so a callback signature generated by one worker
 * verifies on any other — no per-process random secret can cross workers.
 * Domain-separated so the derivation can never collide with other HMAC uses.
 */
function mockWebhookSecret() {
  if (!process.env.JWT_SECRET) {
    throw new paymentConfig.PaymentConfigError(
      'JWT_SECRET is required to derive the mock webhook secret.'
    );
  }
  return crypto.createHmac('sha256', process.env.JWT_SECRET)
    .update('zutsav.mock-webhook.v1')
    .digest('hex');
}

function normalizeMockOutcome(outcome) {
  const o = String(outcome == null ? '' : outcome).trim().toLowerCase();
  if (!paymentConfig.MOCK_OUTCOMES.includes(o)) {
    throw new paymentConfig.PaymentConfigError(
      `Mock payment outcome must be one of ${paymentConfig.MOCK_OUTCOMES.join('|')}.`
    );
  }
  return o;
}

function mockStateEntry(outcome, now = Date.now()) {
  return {
    outcome,
    outcomeExpiresAt: new Date(now + MOCK_OUTCOME_TTL_MS),
    expiresAt:        new Date(now + MOCK_PHYSICAL_TTL_MS),
  };
}

/** Safe read rule shared by the database and memory paths. */
function resolveStoredOutcome(entry) {
  if (!entry) return null;
  if (new Date(entry.outcomeExpiresAt).getTime() <= Date.now()) return 'pending';
  return entry.outcome;
}

/**
 * Drive a mock transaction to an explicit outcome (success|failure|pending).
 * Writes through to the shared store so every worker observes it.
 */
async function setMockOutcome(merchantTransactionId, outcome) {
  const o     = normalizeMockOutcome(outcome);
  const key   = String(merchantTransactionId);
  const entry = mockStateEntry(o);
  if (dbConnected()) {
    await MockPaymentState.findByIdAndUpdate(key, { $set: entry }, { upsert: true });
  }
  mockOutcomes.set(key, entry);
  return o;
}

/** Register a transaction with the configured default outcome at creation. */
async function registerMockOutcome(merchantTransactionId) {
  const key   = String(merchantTransactionId);
  const entry = mockStateEntry(paymentConfig.mockDefaultOutcome());
  if (dbConnected()) {
    await MockPaymentState.updateOne({ _id: key }, { $setOnInsert: entry }, { upsert: true });
  }
  if (!mockOutcomes.has(key)) mockOutcomes.set(key, entry);
}

/**
 * Current outcome for a mock transaction (configured default when never
 * driven). Expired entries read as 'pending' — an explicit failure/pending
 * outcome never degrades into the default success.
 */
async function getMockOutcome(merchantTransactionId) {
  const key = String(merchantTransactionId);
  if (dbConnected()) {
    const doc = await MockPaymentState.findById(key).lean();
    return resolveStoredOutcome(doc) ?? paymentConfig.mockDefaultOutcome();
  }
  return resolveStoredOutcome(mockOutcomes.get(key)) ?? paymentConfig.mockDefaultOutcome();
}

/** Clear all mock transactions (used between automated tests). */
async function resetMockPayments() {
  mockOutcomes.clear();
  if (dbConnected()) await MockPaymentState.deleteMany({});
}

/**
 * Compute a valid mock-mode webhook checksum for a base64 response body.
 * Only exists so local tooling / automated tests can exercise the webhook
 * path in mock mode; mock mode is impossible in production. The secret is
 * derived from JWT_SECRET, so it is identical in every backend worker.
 */
function getMockWebhookChecksum(base64Response) {
  return checksumOf(base64Response, mockWebhookSecret(), MOCK_SALT_INDEX);
}

// ── Gateway config ──────────────────────────────────────────────────────────

const _cfg = () => paymentConfig.resolvePhonePeCredentials();

// ── Create a payment order ──────────────────────────────────────────────────

/**
 * Create a PhonePe payment request.
 * Returns { redirectUrl, merchantTransactionId } (+ `mock: true` in mock mode).
 */
const createPhonePeOrder = async ({ merchantTransactionId, amount, userId, callbackUrl, redirectUrl }) => {
  const cfg = await _cfg();

  // Mock mode: no gateway call, no credentials, no network. The client is
  // sent straight back to the app's own payment-callback page; the mock
  // outcome (default or explicitly driven via the mock control route, shared
  // across workers) is what the existing verify endpoints will read in
  // checkPhonePeStatus.
  if (cfg.mode === 'mock') {
    await registerMockOutcome(merchantTransactionId);
    return { redirectUrl, merchantTransactionId, mock: true };
  }

  const { merchantId, saltKey, saltIndex, baseUrl } = cfg;

  const payload = {
    merchantId,
    merchantTransactionId,
    merchantUserId:    `USR_${userId}`,
    amount:            Math.round(amount * 100),
    redirectUrl,
    redirectMode:      'REDIRECT',
    callbackUrl,
    paymentInstrument: { type: 'PAY_PAGE' },
  };

  const base64Payload = Buffer.from(JSON.stringify(payload)).toString('base64');
  const xVerify       = sha256Hex(base64Payload + '/pg/v1/pay' + saltKey) + '###' + saltIndex;

  const { data } = await axios.post(
    `${baseUrl}/pg/v1/pay`,
    { request: base64Payload },
    {
      headers: {
        'Content-Type':  'application/json',
        'X-VERIFY':      xVerify,
        'X-MERCHANT-ID': merchantId,
      },
      timeout: 15000,
    }
  );

  if (!data?.success) throw new Error(data?.message || 'PhonePe order creation failed');
  return { redirectUrl: data.data?.instrumentResponse?.redirectInfo?.url, merchantTransactionId };
};

// ── Status poll ─────────────────────────────────────────────────────────────

/**
 * Check payment status with PhonePe (or the in-process mock store).
 */
const checkPhonePeStatus = async (merchantTransactionId) => {
  const cfg = await _cfg();

  if (cfg.mode === 'mock') {
    const outcome = await getMockOutcome(merchantTransactionId);
    if (outcome === 'success') {
      return {
        success:       true,
        code:          'PAYMENT_SUCCESS',
        state:         'COMPLETED',
        transactionId: `MOCKTXN_${merchantTransactionId}`,
      };
    }
    if (outcome === 'failure') {
      return { success: false, code: 'PAYMENT_FAILED', state: 'FAILED', transactionId: null };
    }
    return { success: false, code: 'PENDING', state: 'PENDING', transactionId: null };
  }

  const { merchantId, saltKey, saltIndex, baseUrl } = cfg;
  const path     = `/pg/v1/status/${merchantId}/${merchantTransactionId}`;
  const xVerify  = sha256Hex(path + saltKey) + '###' + saltIndex;

  const { data } = await axios.get(
    `${baseUrl}${path}`,
    {
      headers: {
        'Content-Type':  'application/json',
        'X-VERIFY':      xVerify,
        'X-MERCHANT-ID': merchantId,
      },
      timeout: 15000,
    }
  );

  return {
    success:       data?.success && data?.data?.state === 'COMPLETED',
    code:          data?.code,
    state:         data?.data?.state,
    transactionId: data?.data?.transactionId,
  };
};

// ── Webhook verification ────────────────────────────────────────────────────

/**
 * Verify PhonePe webhook callback.
 *
 * Sandbox/live: the checksum must match the EXPLICITLY configured salt key —
 * there is no default salt, so a forged callback signed with PhonePe's
 * publicly documented test salt is rejected.
 * Mock: verified against a secret derived from JWT_SECRET, identical in
 * every backend worker (PhonePe never calls us in mock mode; automated
 * tests use getMockWebhookChecksum()).
 */
const verifyWebhookChecksum = async (base64Response, xVerifyHeader) => {
  const cfg = await _cfg();

  if (cfg.mode === 'mock') {
    return checksumEquals(getMockWebhookChecksum(base64Response), xVerifyHeader);
  }

  return checksumEquals(checksumOf(base64Response, cfg.saltKey, cfg.saltIndex), xVerifyHeader);
};

module.exports = {
  createPhonePeOrder,
  checkPhonePeStatus,
  verifyWebhookChecksum,
  // Mock-mode controls (no effect outside mock mode; unreachable in production)
  setMockOutcome,
  getMockOutcome,
  registerMockOutcome,
  resetMockPayments,
  getMockWebhookChecksum,
  MOCK_OUTCOME_TTL_MS,
  MOCK_PHYSICAL_TTL_MS,
};
